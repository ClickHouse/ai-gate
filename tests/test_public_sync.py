def test_export_diff_apply_are_idempotent(tmp_path):
    exported = tmp_path / "export"
    public = tmp_path / "public"
    ps.export(exported)
    (public / ".github" / "workflows").mkdir(parents=True)
    (public / "README.md").write_text("public only\n")
    (public / ".github" / "workflows" / "test.yml").write_text("public only\n")
    (public / "aigate").mkdir()
    (public / "aigate" / "stale.py").write_text("gone from the private copy\n")
    changes = ps.diff(public, exported)
    assert "D aigate/stale.py" in changes and "A action.yml" in changes
    text = ps.unified(public, exported, changes)
    assert "--- a/aigate/stale.py" in text and "-gone from the private copy" in text
    assert "+++ b/action.yml" in text and "+name: AI review gate" in text
    applied = ps.apply(public, exported)
    assert applied == changes
    assert ps.diff(public, exported) == []  # a second sync is a no-op
    assert ps.unified(public, exported, []) == ""
    assert ps.apply(public, exported) == []
    # Public-only files were not touched.
    assert (public / "README.md").read_text() == "public only\n"
    assert (
        public / ".github" / "workflows" / "test.yml"
    ).read_text() == "public only\n"
    assert not (public / "aigate" / "stale.py").exists()


def test_the_export_equals_the_local_port_on_the_owned_paths(tmp_path):
    # One-time equivalence: the hand-built port that preceded the sync. The
    # first sync after the merge performs the port for real.
    if not PORT.is_dir():
        pytest.skip("the local port is not present (AI_GATE_PUBLIC_PORT)")
    exported = tmp_path / "export"
    ps.export(exported)
    assert ps.diff(PORT, exported) == []


WORKFLOW = HERE.parents[3] / ".github" / "workflows" / "ai-gate-public-sync.yml"


def test_the_sync_workflow_is_a_dry_run_unless_the_repository_variable_says_otherwise():
    if not WORKFLOW.exists():
        pytest.skip("the sync workflow lives in the monorepo")
    wf = yaml.safe_load(WORKFLOW.read_text())
    on = wf.get(True, wf.get("on"))
    assert set(on) == {"push", "workflow_dispatch"} and on["push"]["branches"] == [
        "main"
    ]
    assert on["workflow_dispatch"]["inputs"]["dry_run"]["default"] is True
    (job,) = wf["jobs"].values()
    assert job["environment"] == "ai-gate-public-sync"
    steps = {s.get("name") or s.get("uses"): s for s in job["steps"]}
    push = steps["Apply and push"]
    assert "vars.AI_GATE_PUBLIC_SYNC_ENABLED == 'true'" in push["if"]
    assert "steps.diff.outputs.changed == 'true'" in push["if"]
    assert "inputs.dry_run" in push["if"]
    assert "vars.AI_GATE_PUBLIC_SYNC_ENABLED != 'true'" in steps["Dry run notice"]["if"]
    (mint,) = [
        s
        for s in job["steps"]
        if str(s.get("uses", "")).startswith("actions/create-github-app-token@")
    ]
    assert mint["with"]["repositories"] == "ai-gate"
    assert mint["with"]["permission-contents"] == "write"
    assert mint["with"]["permission-workflows"] == "write"
    assert mint["with"]["permission-metadata"] == "read"
    assert {k for k in mint["with"] if k.startswith("permission-")} == {
        "permission-contents",
        "permission-workflows",
        "permission-metadata",
    }
    (checkout,) = [
        s
        for s in job["steps"]
        if str(s.get("uses", "")).startswith("actions/checkout@")
    ]
    assert (
        checkout["with"]["ref"] == "${{ github.sha }}"
        and checkout["with"]["persist-credentials"] is False
    )
    # No other secret than the App's reaches the job.
    assert set(re.findall(r"secrets\.([A-Z_]+)", yaml.safe_dump(job, width=10**6))) == {
        "AI_GATE_PUBLIC_SYNC_APP_ID",
        "AI_GATE_PUBLIC_SYNC_APP_PRIVATE_KEY",
    }
